test("one camera can bypass global VA-API transcode while other cameras use the dynamic input filter", async () => {
  const dir = mkdtempSync(join(tmpdir(), "ewb-go2rtc-camera-egress-"));
  const cfg = { go2rtcConfig: join(dir, "go2rtc.yaml"), selfHost: "127.0.0.1", port: 3000,
    go2rtcBin: "go2rtc", go2rtcTranscode: "always", go2rtcMaxHeight: 720, go2rtcVaapiDevice: "/dev/dri/renderD128" };
  const cams = [{ sn: "FRONT", enabled: true }, { sn: "BALCONY", enabled: true, transcode: "never" }];
  const state = createState();
  state.slots.set("FRONT", { codec: "h264" });
  state.slots.set("BALCONY", { codec: "h265" });
  await createGo2rtc({ cfg, state, platform: "linux", listCameras: () => cams }).writeGo2rtc();
  const y = parse(readFileSync(cfg.go2rtcConfig, "utf8"));
  assert.equal(y.streams.BALCONY, "ffmpeg:http://127.0.0.1:3000/stream/BALCONY?format=mpegts&pes=fragmented#input=ewb_timestamped_http#video=copy");
  assert.equal(y.streams.FRONT, "ffmpeg:http://127.0.0.1:3000/stream/FRONT?format=mpegts&pes=fragmented#input=ewb_dynamic_http#video=tvh264");
  assert.match(y.ffmpeg.ewb_dynamic_http, /^--eufy-vaapi \/dev\/dri\/renderD128 720 auto /);
  assert.match(y.ffmpeg.ewb_dynamic_http, /-reinit_filter 0 -f mpegts.*-i \{input\}/);
  assert.match(y.ffmpeg.bin, /ffmpeg-hardware\.mjs$/);
  assert.match(y.ffmpeg.tvh264, /-vf ewb_scale -codec:v ewb_encoder -profile:v main/);
  assert.match(y.ffmpeg.tvh264, /-fps_mode:v passthrough -enc_time_base:v 1:90000/);
  assert.match(y.ffmpeg.output, /\{output\}#killsignal=15#killtimeout=2$/);
});

