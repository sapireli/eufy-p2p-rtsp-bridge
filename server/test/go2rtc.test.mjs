import { test, before, after } from "node:test";
import assert from "node:assert/strict";
import { mkdtempSync, readFileSync } from "node:fs";
import { join } from "node:path";
import { tmpdir } from "node:os";
import { parse } from "yaml";
import { createGo2rtc, hardenGo2rtcYaml, withNamedStreams, streamKeys, streamSlug, execSourceFor } from "../src/go2rtc.mjs";
import { createState } from "../src/state.mjs";

const originals = {};
before(() => { for (const k of ["log", "warn", "error"]) { originals[k] = console[k]; console[k] = () => {}; } });
after(() => { for (const k of ["log", "warn", "error"]) console[k] = originals[k]; });

test("writeGo2rtc: one ffmpeg copy source per enabled camera, API on loopback only, webrtc off", async () => {
  const dir = mkdtempSync(join(tmpdir(), "ewb-go2rtc-"));
  const cfg = { go2rtcConfig: join(dir, "nested", "go2rtc.yaml"), selfHost: "127.0.0.1", port: 3000, go2rtcBin: "go2rtc" };
  const cams = [{ sn: "T8410A", enabled: true }, { sn: "T8113B", enabled: false }, { sn: "T8214C", enabled: true }];
  const g = createGo2rtc({ cfg, state: createState(), listCameras: () => cams });
  const sns = await g.writeGo2rtc();
  assert.deepEqual(sns, ["T8410A", "T8214C"]);
  const text = readFileSync(cfg.go2rtcConfig, "utf8");
  const y = parse(text);
  assert.equal(y.api.listen, "127.0.0.1:1984", "go2rtc API must not be reachable off-host");
  assert.equal(y.webrtc.listen, "", "webrtc disabled (empty listen; go2rtc defaults it ON when the block is absent)");
  assert.equal(y.rtsp.listen, ":8554", "RTSP stays on all interfaces for the display clients");
  assert.deepEqual(y.streams, {
    T8410A: "ffmpeg:http://127.0.0.1:3000/stream/T8410A#video=copy",
    T8214C: "ffmpeg:http://127.0.0.1:3000/stream/T8214C#video=copy",
  });
  assert.match(text, /^# generated by/, "generator header comment preserved");
  assert.doesNotMatch(text, /8555/);
});

test("hardenGo2rtcYaml is idempotent and tolerates a file without webrtc", () => {
  const once = hardenGo2rtcYaml('api:\n  listen: ":1984"\nrtsp:\n  listen: ":8554"\nstreams: {}\n');
  assert.equal(parse(once).api.listen, "127.0.0.1:1984");
  assert.equal(parse(once).webrtc.listen, "");
  assert.equal(hardenGo2rtcYaml(once), once);
});

// go2rtc lists stream keys, and a wall of serial numbers tells an operator nothing about which camera
// they are looking at. The key IS the name — no serial stream is kept alongside it.
test("streams are keyed by the camera's name, not its serial", () => {
  const yaml = "streams:\n  T8214A: ffmpeg:http://127.0.0.1:3000/stream/T8214A#video=copy\n";
  const out = withNamedStreams(yaml, [{ sn: "T8214A", name: "Front Door" }]);
  assert.match(out, /front_door: ffmpeg:http:\/\/127\.0\.0\.1:3000\/stream\/T8214A#video=copy/);
  assert.doesNotMatch(out, /T8214A:/, "the serial key is replaced, not duplicated");
  assert.equal((out.match(/ffmpeg:/g) ?? []).length, 1, "exactly one producer per camera");
});

// A camera must stay reachable even when its name cannot be used, and must never answer for another.
test("a name that slugs to nothing or collides falls back to the serial", () => {
  const keys = streamKeys([
    { sn: "T8214A", name: "Front Door" },
    { sn: "T8425B", name: "front door" }, // same slug as the first
    { sn: "T8030C", name: "!!!" }, // slugs to nothing
  ]);
  assert.equal(keys.get("T8214A"), "front_door");
  assert.equal(keys.get("T8425B"), "T8425B", "the second camera keeps its serial rather than stealing the name");
  assert.equal(keys.get("T8030C"), "T8030C");
});

test("the source is carried across unchanged, including its transcode suffix", () => {
  const yaml = "streams:\n  T8425B: ffmpeg:http://127.0.0.1:3000/stream/T8425B#video=h264#hardware\n";
  const out = withNamedStreams(yaml, [{ sn: "T8425B", name: "Garage Cam" }]);
  assert.match(out, /garage_cam: ffmpeg:http:\/\/127\.0\.0\.1:3000\/stream\/T8425B#video=h264#hardware/);
});

test("streamSlug makes URL-safe keys", () => {
  assert.equal(streamSlug("Solar Wall Light Cam"), "solar_wall_light_cam");
  assert.equal(streamSlug("  Garage – Interior/Door  "), "garage_interior_door");
  assert.equal(streamSlug(""), "");
});

// Probing consumes DATA, not time, so a low-bitrate camera can outlast go2rtc's exec timeout while a
// high-bitrate one probes in seconds. Naming the codec removes that difference.
test("a passthrough stream with a known codec is handed to ffmpeg with the format named", () => {
  const src = execSourceFor("http://127.0.0.1:3000/stream/T8423A", "h265", "#video=copy");
  assert.match(src, /^exec:ffmpeg /);
  assert.match(src, / -f hevc /, "hevc, not h265 — that is ffmpeg's demuxer name");
  assert.match(src, /-i http:\/\/127\.0\.0\.1:3000\/stream\/T8423A /);
  assert.match(src, /-f rtsp \{output\}$/, "go2rtc substitutes its own publish target");
});

test("h264 cameras get their own format, not hevc", () => {
  assert.match(execSourceFor("http://x/s/A", "h264", "#video=copy"), / -f h264 /);
});

// Two cases must fall back to go2rtc's own ffmpeg: source rather than a hand-written command.
test("an unknown codec or a transcode falls back to go2rtc's own source", () => {
  assert.equal(execSourceFor("http://x/s/A", undefined, "#video=copy"), "", "first open still has to probe");
  assert.equal(
    execSourceFor("http://x/s/A", "h265", "#video=h264#hardware"),
    "",
    "go2rtc's templates pick the platform's hardware encoder better than a hand-written command",
  );
});
